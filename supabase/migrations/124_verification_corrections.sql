-- ── Corrections from the source-verification pass ───────────────────────────
-- Three agents checked 15 recurring series against each event's own source
-- page. This applies only the changes the source positively PROVES wrong.
-- Time changes and missing-date additions are deliberately NOT here: those
-- need a human call, and are listed at the bottom.

-- ── 1. Restore Karaoke From Hell on Mon 2026-11-30 (our own regression) ─────
-- Nov 30 had two identical rows after migration 121 shifted one off Sunday.
-- The admin rejected one in the app; migration 122 rejected the other. Both
-- went, so Dante's next show — five days out — fell off the wall entirely.
-- Dante's lists it: "Mon November 30, 2026 / Show: 09:00 pm".
-- Restores exactly one, the earliest-created, and only if none is published.
update public.events
   set status = 'published', rejection_reason = null, rejection_note = null, reviewed_at = null
 where id = (
   select id from public.events
    where title ilike '%Karaoke From Hell%'
      and (starts_at at time zone 'America/Los_Angeles')::date = date '2026-11-30'
      and status <> 'published'
    order by created_at
    limit 1)
   and not exists (
     select 1 from public.events
      where title ilike '%Karaoke From Hell%'
        and (starts_at at time zone 'America/Los_Angeles')::date = date '2026-11-30'
        and status = 'published');

-- ── 2. Open Court — a date the venue does not hold ──────────────────────────
-- crowdwork publishes Dec 9 then Dec 23. Asked for the Dec 16 occurrence
-- directly it answers "That specific date doesn't exist." Our weekly rule
-- invented it.
update public.events
   set status = 'rejected', rejection_reason = 'wrong_date',
       rejection_note = 'crowdwork publishes Dec 9 then Dec 23; the Dec 16 occurrence does not exist. Generated by a weekly rule the venue does not follow.',
       reviewed_at = now()
 where title ilike '%Open Court%'
   and status = 'published'
   and (starts_at at time zone 'America/Los_Angeles')::date = date '2026-12-16';

-- ── 3. Beaumont Cribbage Club — Saturdays only ──────────────────────────────
-- Source: "Saturdays at 2:30 PM (registration 2:00-2:25 PM)" and "every
-- Saturday afternoon". The word Thursday appears nowhere on the page, and no
-- 7 PM session exists in any occurrence. Three Thursdays and a 19:00 Saturday
-- are inventions.
update public.events
   set status = 'rejected', rejection_reason = 'wrong_date',
       rejection_note = 'Source is Saturdays at 2:30 PM only; no Thursday session and no 7 PM session exists.',
       reviewed_at = now()
 where title ilike '%Beaumont Cribbage%'
   and status = 'published'
   and starts_at > now()
   and (
     extract(dow from (starts_at at time zone 'America/Los_Angeles')) = 4   -- Thursday
     or (starts_at at time zone 'America/Los_Angeles')::time = time '19:00'
   );

-- ── 4. FAN EXPO Portland 2027 — opens Friday, not Thursday ─────────────────
-- Source: "January 29 to 31", "Friday 4 PM - 9 PM", "Saturday 10 AM - 7 PM",
-- "Sunday 10 AM - 5 PM". In 2027 Jan 29 is a Friday. No Thursday, no preview
-- night. The Thursday row is the one-day-early pattern again.
update public.events
   set status = 'rejected', rejection_reason = 'wrong_date',
       rejection_note = 'Source runs Jan 29-31 2027 (Fri-Sun). There is no Thursday Jan 28 day.',
       reviewed_at = now()
 where title ilike '%FAN EXPO Portland%'
   and status = 'published'
   and (starts_at at time zone 'America/Los_Angeles')::date = date '2027-01-28';

